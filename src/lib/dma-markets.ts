export const DMA_NAMES = new Set(DMA_MARKETS.map((d) => d.market.toLowerCase()))

export function isKnownDma(name: string): boolean {
  return DMA_NAMES.has(name.trim().toLowerCase())
}

export function searchDmas(query: string, limit = 12): { rank: number; market: string }[] {
  const q = query.trim().toLowerCase()
  if (!q) return DMA_MARKETS.slice(0, limit)
  return DMA_MARKETS.filter((d) => d.market.toLowerCase().includes(q)).slice(0, limit)
}
